// The project folder is "Havana App" (with a space). Two expo-constants iOS build steps break on spaces:
// the podspec runs the script path unquoted, and the script calls `basename $PROJECT_DIR` unquoted
// (which silently skips generating app.config). Quote both. Runs on every `npm install` (postinstall).
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..', 'node_modules', 'expo-constants');
const edits = [
  ['ios/EXConstants.podspec', '"bash -l -c \\"#{env_vars}$PODS_TARGET_SRCROOT/../scripts/get-app-config-ios.sh\\""', '"bash -l -c \\"#{env_vars}\'$PODS_TARGET_SRCROOT/../scripts/get-app-config-ios.sh\'\\""'],
  ['scripts/get-app-config-ios.sh', 'PROJECT_DIR_BASENAME=$(basename $PROJECT_DIR)', 'PROJECT_DIR_BASENAME=$(basename "$PROJECT_DIR")'],
];
// The generated Xcode project runs react-native-xcode.sh through an unquoted `...` substitution too.
// (ios/ is regenerated by `expo prebuild`; run `node scripts/fix-ios-paths.cjs` again after a prebuild.)
const pbx = path.join(__dirname, '..', 'ios', 'Havana.xcodeproj', 'project.pbxproj');
if (fs.existsSync(pbx)) {
  const s = fs.readFileSync(pbx, 'utf8');
  const from = '`\\"$NODE_BINARY\\" --print \\"require(\'path\').dirname(require.resolve(\'react-native/package.json\')) + \'/scripts/react-native-xcode.sh\'\\"`';
  const to = '\\"$(\\"$NODE_BINARY\\" --print \\"require(\'path\').dirname(require.resolve(\'react-native/package.json\')) + \'/scripts/react-native-xcode.sh\'\\")\\"';
  if (s.includes(from)) fs.writeFileSync(pbx, s.replace(from, to));
}
for (const [file, from, to] of edits) {
  const p = path.join(root, file);
  if (!fs.existsSync(p)) continue;
  const s = fs.readFileSync(p, 'utf8');
  if (s.includes(from)) fs.writeFileSync(p, s.replace(from, to));
}
